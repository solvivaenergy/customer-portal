/**
 * Generates src/content/faqs.ts from the public FAQ on solvivaenergy.com so the portal shows the same
 * questions and answers as the website. Reads https://www.solvivaenergy.com/faq for the category list
 * (site order) and each /faqs-categories/<slug> page for its questions; answers are Webflow rich text
 * and are reduced to paragraphs and bullet lists. Marketing owns the copy on the website.
 * Run after the website FAQ changes:  node scripts/sync-faqs.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SITE = "https://www.solvivaenergy.com";
const ROOT = path.resolve(new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const OUT = path.join(ROOT, "src/content/faqs.ts");

async function page(url) {
  const res = await fetch(url, { headers: { "user-agent": "Mozilla/5.0 (solviva-customer-portal sync-faqs)" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };
const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m)
    .replace(/ /g, " ");

/** Inner text of an HTML fragment: <br> becomes a newline, every other tag is dropped. */
const text = (fragment) =>
  decode(fragment.replace(/<br\s*\/?>/gi, "\n").replace(/<[^>]+>/g, ""))
    .split("\n")
    .map((l) => l.replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .join("\n");

/** The content of the element whose opening tag starts at `start`, tracking nested tags of the same name. */
function inner(html, start, tag) {
  const open = html.indexOf(">", start) + 1;
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, "gi");
  re.lastIndex = open;
  let depth = 1;
  for (let m; (m = re.exec(html)); ) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return html.slice(open, m.index);
  }
  throw new Error(`unclosed <${tag}>`);
}

/** Rich-text answer → blocks. A paragraph whose lines all start with "- " is a list the editor typed by hand. */
function blocks(answerHtml) {
  const out = [];
  const re = /<(p|ul|ol)\b[^>]*>/gi;
  for (let m; (m = re.exec(answerHtml)); ) {
    const tag = m[1].toLowerCase();
    const body = inner(answerHtml, m.index, tag);
    re.lastIndex = m.index + body.length;
    if (tag === "p") {
      const t = text(body);
      if (!t) continue;
      const lines = t.split("\n");
      if (lines.length > 1 && lines.every((l) => /^[-•]\s/.test(l))) out.push({ type: "ul", items: lines.map((l) => l.replace(/^[-•]\s+/, "")) });
      else out.push({ type: "p", text: t });
    } else {
      const items = [...body.matchAll(/<li\b[^>]*>([\s\S]*?)<\/li>/gi)].map((li) => text(li[1])).filter(Boolean);
      if (items.length) out.push({ type: "ul", items });
    }
  }
  if (!out.length) {
    const t = text(answerHtml);
    if (t) out.push({ type: "p", text: t });
  }
  return out;
}

/** [question, answerHtml] pairs from a Webflow FAQ list (Finsweet CMS filter fields). */
function pairs(html) {
  const out = [];
  const qre = /<(h[1-6]|div)\b[^>]*fs-cmsfilter-field="question"[^>]*>/gi;
  for (let q; (q = qre.exec(html)); ) {
    const question = text(inner(html, q.index, q[1]));
    const a = html.indexOf('fs-cmsfilter-field="answer"', q.index);
    if (a === -1) break;
    const start = html.lastIndexOf("<div", a);
    out.push([question, inner(html, start, "div")]);
  }
  return out;
}

const index = await page(`${SITE}/faq`);
const categories = [...index.matchAll(/href="(\/faqs-categories\/[a-z0-9-]+)"[^>]*>[\s\S]*?class="title-faq-answer">([^<]+)</g)].map((m) => ({ path: m[1], name: decode(m[2]).trim() }));
if (!categories.length) throw new Error("no FAQ categories found on /faq — has the page structure changed?");

const faqs = new Map(); // question → { q, a, categories }
for (const c of categories) {
  for (const [q, a] of pairs(await page(SITE + c.path))) {
    const entry = faqs.get(q) ?? { q, a: blocks(a), categories: [] };
    if (!entry.categories.includes(c.name)) entry.categories.push(c.name);
    faqs.set(q, entry);
  }
}
// Questions featured on /faq that belong to no category.
for (const [q, a] of pairs(index)) if (!faqs.has(q)) faqs.set(q, { q, a: blocks(a), categories: ["General"] });
if (!faqs.size) throw new Error("no questions found");

const names = categories.map((c) => c.name);
if ([...faqs.values()].some((f) => f.categories[0] === "General")) names.push("General");

const header = `/* Generated by scripts/sync-faqs.mjs from ${SITE}/faq on ${new Date().toISOString().slice(0, 10)}. Do not hand-edit; re-run the script. */\n`;
const types = `export type FaqBlock = { type: "p"; text: string } | { type: "ul"; items: string[] };\nexport type Faq = { q: string; a: FaqBlock[]; /** Website categories the question appears in, in site order. */ categories: string[] };\n`;
const body = `\n/** FAQ categories in the order the website lists them. */\nexport const FAQ_CATEGORIES: string[] = ${JSON.stringify(names)};\n\nexport const FAQS: Faq[] = ${JSON.stringify([...faqs.values()], null, 2)};\n`;
fs.writeFileSync(OUT, header + types + body);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${faqs.size} questions in ${names.length} categories`);
