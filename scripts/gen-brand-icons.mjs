/**
 * Generates src/components/brand.tsx from the Figma SVG exports in src/assets/brand.
 * One React component per file; <g clip-path> wrappers and <defs> are dropped (every export
 * fits its own viewBox). Run after adding or replacing an SVG:  node scripts/gen-brand-icons.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const SRC = path.join(ROOT, "src/assets/brand");
const OUT = path.join(ROOT, "src/components/brand.tsx");

// file → component name, doc comment, and an optional fill to replace with currentColor.
const ICONS = {
  "logo-horizontal.svg": { name: "SolvivaLogoHorizontal", doc: 'Horizontal lockup: sunburst + SOLVIVA + "An AboitizPower Company". Coloured with `currentColor`.', recolor: "#FCFCFC", label: "Solviva — An AboitizPower Company" },
  "coins.svg": { name: "CoinsIcon", doc: 'Coins with sparkles (Figma "Frame 29") — Total savings from solar.' },
  "handshake.svg": { name: "HandshakeIcon", doc: 'Handshake (Figma "Handshake 1") — Referral earnings.' },
  "support-ticket.svg": { name: "SupportTicketIcon", doc: 'Agent with headset (Figma "Frame 264") — Submit a support ticket.' },
  "pms-tools.svg": { name: "PmsToolsIcon", doc: 'Crossed wrench and screwdriver (Figma "Layer_1") — Request PMS.' },
  "phone-call.svg": { name: "PhoneCallIcon", doc: 'Phone handset (Figma "phone-call") — Contact support.' },
};

let out = `/* Generated by scripts/gen-brand-icons.mjs from src/assets/brand/*.svg (Figma exports). Do not hand-edit. */\nimport type { SVGProps } from "react";\n`;
for (const [file, meta] of Object.entries(ICONS)) {
  const svg = fs.readFileSync(path.join(SRC, file), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 48 48";
  let paths = svg.match(/<path [^>]*\/>/g) ?? [];
  if (meta.recolor) paths = paths.map((p) => p.replace(`fill="${meta.recolor}"`, 'fill="currentColor"'));
  const a11y = meta.label ? `role="img" aria-label="${meta.label}"` : 'aria-hidden="true"';
  out += `\n/** ${meta.doc} */\nexport function ${meta.name}(props: SVGProps<SVGSVGElement>) {\n  return (\n    <svg viewBox="${viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg" ${a11y} {...props}>\n      ${paths.join("\n      ")}\n    </svg>\n  );\n}\n`;
}
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(ICONS).length} components`);
